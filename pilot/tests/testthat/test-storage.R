test_that('single writer, stale revision, failure and replay are enforced', {
 b<-mem_backend();cfg<-list(writer='operator',hosted=FALSE);st<-new_store(b,cfg)
 expect_error(st$claim(list(user='reader',role='reader'),'a'),'Editor');expect_error(st$claim(list(user='other',role='admin'),'a'),'designated')
 st$claim(editor,'a');expect_error(st$claim(editor,'b'),'Another')
 s<-st$commit(editor,'a',0,'one',function(s) record(s,editor,'Saved'));expect_equal(s$revision,1)
 expect_equal(st$commit(editor,'a',0,'one',function(s) stop('Must not execute'))$revision,1)
 expect_error(st$commit(editor,'a',0,'two',identity),'changed')
 b$env$fail<-TRUE;expect_error(st$commit(editor,'a',1,'two',identity),'persistence');expect_equal(st$read()$revision,1)
 b$env$fail<-FALSE;st$release('a');expect_silent(st$claim(editor,'b'))
 expect_error(new_store(b,list(writer='operator',hosted=TRUE,single_process=FALSE))$claim(editor,'a'),'single-process')
})
test_that('pins survive restart, preserve versions and restore backups', {
 path<-tempfile();dir.create(path);board<-pins::board_folder(path,versioned=TRUE);b<-pin_backend(board,'state',TRUE);cfg<-list(writer='operator',hosted=FALSE)
 st<-new_store(b,cfg);st$commit(editor,'a',0,'one',identity);st$commit(editor,'a',1,'two',identity)
 restarted<-new_store(pin_backend(board,'state'),cfg);expect_equal(restarted$read()$revision,2);expect_gte(nrow(pins::pin_versions(board,'state')),2)
 expect_error(pin_backend(board,'missing')$read(),'missing')
 saveRDS(restarted$read(),file.path(path,'backup.rds'));expect_identical(validate_state(readRDS(file.path(path,'backup.rds'))),restarted$read())
})
test_that('hosted identity determines role', {
 cfg<-list(hosted=TRUE,writer='operator',admins='admin')
 expect_equal(actor_for(list(user=NULL),cfg)$role,'reader');expect_equal(actor_for(list(user='operator'),cfg)$role,'editor')
 expect_error(require_role(actor_for(list(user='operator'),cfg),TRUE),'Administrator');expect_equal(actor_for(list(user='admin'),cfg)$role,'admin')
})
