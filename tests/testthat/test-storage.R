test_that('host process lock separates environments and excludes another worker', {
 cfg<-list(hosted=TRUE,pin=paste0('test-',basename(tempfile())))
 lock<-acquire_process_lock(cfg);on.exit(filelock::unlock(lock),add=TRUE)
 other<-acquire_process_lock(list(hosted=TRUE,pin=paste0(cfg$pin,'-other')));expect_s3_class(other,'filelock_lock');filelock::unlock(other)
 path<-file.path('/tmp',paste0('olsd-writer-',digest::digest(list(Sys.getenv('CONNECT_SERVER'),cfg$pin),algo='sha256'),'.lock'))
 script<-tempfile(fileext='.R');writeLines("l<-filelock::lock(commandArgs(TRUE)[[1]],timeout=0);quit(status=if(is.null(l)) 0 else 9)",script)
 expect_equal(system2(file.path(R.home('bin'),'Rscript'),c(shQuote(script),shQuote(path))),0)
})
test_that('artifact paths stay short and distinct in nested local projects', {
 cfg<-list(pin='olsd-catalog-state',backend='folder')
 identity<-paste(rep('a',64),collapse='')
 name<-artifact_pin_name(cfg,'snapshot',identity)
 expect_equal(nchar(name),29)
 base<-file.path(tempdir(),paste(rep('d',80),collapse=''));dir.create(base,recursive=TRUE)
 full<-file.path(base,name,'20261104T000000Z-12345',paste0(name,'.rds'))
 expect_lt(nchar(full),260)
 old_name<-paste0(cfg$pin,'-snapshot-',identity)
 expect_gt(nchar(file.path(base,old_name,'20261104T000000Z-12345',paste0(old_name,'.rds'))),260)
 board<-pins::board_folder(base,versioned=TRUE);pin_write_versioned(board,list(full_hash=identity),name)
 expect_equal(pins::pin_read(board,name)$full_hash,identity)
 expect_identical(name,artifact_pin_name(cfg,'snapshot',identity))
 expect_false(identical(name,artifact_pin_name(cfg,'export',identity)))
 expect_false(identical(name,artifact_pin_name(list(pin='other-state',backend='folder'),'snapshot',identity)))
 expect_match(artifact_pin_name(list(pin='owner/state',backend='connect'),'export',identity),'^owner/file-')
})
